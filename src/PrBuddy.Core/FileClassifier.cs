namespace PrBuddy.Core;

public enum FileKind { Code, Test, Generated, BuildConfig, Other }

/// <summary>Path-based guesses about what a file is. Cheap and deliberately conservative.</summary>
public static class FileClassifier
{
    static readonly HashSet<string> TestDirectories = new(StringComparer.OrdinalIgnoreCase) { "test", "tests", "spec", "specs" };
    static readonly string[] TestDirectorySuffixes = [".tests", ".test", ".unittests", ".integrationtests", ".specs"];
    static readonly HashSet<string> TestProjectParts = new(StringComparer.OrdinalIgnoreCase)
        { "Tests", "Test", "UnitTests", "IntegrationTests", "Specs" };
    static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];
    static readonly string[] ProjectExtensions = [".csproj", ".fsproj", ".vbproj", ".props", ".targets"];
    static readonly string[] BuildConfigExtensions = [".globalconfig", ".ruleset"];

    static readonly HashSet<string> BuildConfigNames = new(StringComparer.OrdinalIgnoreCase)
    {
        ".editorconfig", "global.json", "nuget.config", ".gitlab-ci.yml", "azure-pipelines.yml", "Jenkinsfile",
        "Directory.Build.props", "Directory.Build.targets", "Directory.Packages.props",
        Configuration.PrBuddyConfig.FileName,
    };

    public static bool IsCSharp(string path) => path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase);

    public static bool IsProjectFile(string path) =>
        ProjectExtensions.Any(e => path.EndsWith(e, StringComparison.OrdinalIgnoreCase));

    public static bool IsTestFile(string path)
    {
        var segments = Normalize(path).Split('/');
        var directories = segments[..^1];
        if (directories.Any(d => TestDirectories.Contains(d) ||
                                 TestDirectorySuffixes.Any(s => d.EndsWith(s, StringComparison.OrdinalIgnoreCase)) ||
                                 // "App.Tests.Unit", "App.UnitTests.Core": a dotted project name with a test part.
                                 d.Split('.').Skip(1).Any(TestProjectParts.Contains)))
            return true;

        // Case-sensitive on purpose: "FooTests.cs" yes, "latest.cs" no.
        var name = System.IO.Path.GetFileNameWithoutExtension(segments[^1]);
        return name.EndsWith("Tests", StringComparison.Ordinal) || name.EndsWith("Test", StringComparison.Ordinal);
    }

    public static bool IsGenerated(string path, string? content)
    {
        if (GeneratedSuffixes.Any(s => path.EndsWith(s, StringComparison.OrdinalIgnoreCase)))
            return true;
        if (content is null) return false;
        var head = content.Length > 500 ? content[..500] : content;
        return head.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>Files that change how everything else is built, analyzed or checked in CI.</summary>
    public static bool IsBuildConfig(string path)
    {
        var normalized = Normalize(path);
        var name = System.IO.Path.GetFileName(normalized);
        return BuildConfigNames.Contains(name)
            || BuildConfigExtensions.Any(e => name.EndsWith(e, StringComparison.OrdinalIgnoreCase))
            || normalized.StartsWith(".github/workflows/", StringComparison.OrdinalIgnoreCase);
    }

    static string Normalize(string path) => path.Replace('\\', '/');
}
